end

-- ============================================================
-- Main run loop (LOVE2D entry points)
-- ============================================================

function Backend.run(env, pState, P)
  _P      = P
  _env    = env
  _pState = pState

  -- Override LOVE2D callbacks so the sketch drives the window

  function love.update(dt)
    -- Update mouse state
    local mx, my = love.mouse.getPosition()
    local mb1    = love.mouse.isDown(1)
    local btn    = nil
    if love.mouse.isDown(1) then btn = "LEFT"
    elseif love.mouse.isDown(2) then btn = "RIGHT"
    elseif love.mouse.isDown(3) then btn = "CENTER" end
    P._setMouse(mx, my, mb1, btn)
  end

  function love.draw()
    P._frame(env)
  end

  function love.keypressed(key, scancode, isrepeat)
    P._setKey(true, key, love.keyboard.getScancodeFromKey(key) or 0)
    local kp = env.keyPressed or rawget(_G or {}, "keyPressed")
    if type(kp) == "function" then kp() end
  end

  function love.keyreleased(key)
    P._setKey(false, "", 0)
    local kr = env.keyReleased or rawget(_G or {}, "keyReleased")
    if type(kr) == "function" then kr() end
  end

  function love.mousepressed(x, y, button)
    local mp = env.mousePressed or rawget(_G or {}, "mousePressed")
    if type(mp) == "function" then mp() end
  end

  function love.mousereleased(x, y, button)
    local mr = env.mouseReleased or rawget(_G or {}, "mouseReleased")
    if type(mr) == "function" then mr() end
  end

  function love.mousemoved(x, y, dx, dy)
    local mm = env.mouseMoved or rawget(_G or {}, "mouseMoved")
    if type(mm) == "function" then mm() end
  end

  function love.quit()
    local ef = env.exit or rawget(_G or {}, "exit")
    if type(ef) == "function" then ef() end
  end

  -- LOVE2D launches its loop automatically; no explicit loop needed here.
end

return Backend
